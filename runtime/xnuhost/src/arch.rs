//! Port of arch_aarch64.S: the seams between the hosted kernel's context and xnuhost's own (docs/booter.md, "Two
//! contexts"). Kernel context: XNU's stack, XNU's TPIDR_EL0 and x18. Host context: this thread's libc TLS, x18 and
//! host stack. Offsets are [`XhCpu`]'s (hostcall.h), taken from the struct itself.
//!
//! - `xh_hc_NAME(cpu, ...)`: the host-call thunks of the vector: switch to the host's TPIDR_EL0, x18 and stack, call
//!   the Rust implementation (hostcalls.rs), switch back and deliver an interrupt noted meanwhile (kctx.rs).
//! - `xh_sig_entry`: every signal of a vCPU thread enters here: the host's TPIDR_EL0 and x18 before any Rust runs.
//! - `xh_upcall_tramp`: where a diverted kernel context lands (cpu.rs divert).
//! - `xh_arch_enter`, `xh_arch_sigreturn`: into the kernel for good, and frame_resume's last step.
//!
//! The task stub (runtime/xnuhost/stub, a flat blob that build.rs makes) is [`STUB`].

/// The task stub, copied into every task's stub region (task.rs).
#[cfg(xh_machine)]
pub static STUB: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/stub.bin"));

#[cfg(all(xh_machine, not(test)))]
mod seams {
    use crate::{cpu, hostcalls as h, kctx};
    use std::mem::offset_of;
    use xnuhost_abi::XhCpu;

    core::arch::global_asm!(
        // ---- host calls: xh_hc_NAME(cpu, ...) -> the Rust NAME(cpu, ...) on the host stack ------------------------
        ".macro HOSTCALL name, target",
        ".text",
        ".globl xh_hc_\\name",
        ".type xh_hc_\\name, %function",
        ".p2align 2",
        "xh_hc_\\name:",
        "stp x29, x30, [sp, #-48]!",
        "mov x29, sp",
        "stp x19, x20, [sp, #16]",
        "str x21, [sp, #32]",
        "mov x19, x0",
        "mov w9, #1",
        "str w9, [x19, #{in_host}]", // from here an interrupt is only noted
        "mrs x9, tpidr_el0",
        "str x9, [x19, #{k_tpidr}]",
        "str x18, [x19, #{k_x18}]",
        "ldr x9, [x19, #{h_tpidr}]",
        "msr tpidr_el0, x9",
        "ldr x18, [x19, #{h_x18}]",
        "mov x20, sp",
        "ldr x9, [x19, #{h_sp}]",
        "mov sp, x9",
        "bl \\target",
        "mov sp, x20",
        "ldr x9, [x19, #{k_tpidr}]",
        "msr tpidr_el0, x9",
        "ldr x18, [x19, #{k_x18}]",
        "str wzr, [x19, #{in_host}]",
        "ldr w9, [x19, #{pending}]", // an interrupt noted meanwhile, and not masked:
        "cbz w9, 1f",                // deliver it now, in kernel context
        "ldr w9, [x19, #{masked}]",
        "cbnz w9, 1f",
        "mov x21, x0",
        "mov x0, x19",
        "adr x1, 2f", // the frame's pc: here
        "mov x2, sp", // and its sp
        "bl {irq_poll}",
        "2:",
        "mov x0, x21",
        "1:",
        "ldr x21, [sp, #32]",
        "ldp x19, x20, [sp, #16]",
        "ldp x29, x30, [sp], #48",
        "ret",
        ".size xh_hc_\\name, . - xh_hc_\\name",
        ".endm",
        "HOSTCALL console_write, {console_write}",
        "HOSTCALL halt, {halt}",
        "HOSTCALL ready, {ready}",
        "HOSTCALL set_upcalls, {set_upcalls}",
        "HOSTCALL wall_time, {wall_time}",
        "HOSTCALL cpu_start, {cpu_start}",
        "HOSTCALL cpu_idle, {cpu_idle}",
        "HOSTCALL irq_ack, {irq_ack}",
        "HOSTCALL irq_eoi, {irq_eoi}",
        "HOSTCALL irq_enable, {irq_enable}",
        "HOSTCALL ipi, {ipi}",
        "HOSTCALL timer_set, {timer_set}",
        "HOSTCALL frame_resume, {frame_resume}",
        "HOSTCALL io_map, {io_map}",
        "HOSTCALL mmio_read, {mmio_read}",
        "HOSTCALL mmio_write, {mmio_write}",
        "HOSTCALL ram_discard, {ram_discard}",
        "HOSTCALL text_fixup, {text_fixup}",
        "HOSTCALL task_create, {task_create}",
        "HOSTCALL task_destroy, {task_destroy}",
        "HOSTCALL task_map, {task_map}",
        "HOSTCALL task_unmap, {task_unmap}",
        "HOSTCALL task_protect, {task_protect}",
        "HOSTCALL task_read, {task_read}",
        "HOSTCALL task_write, {task_write}",
        "HOSTCALL thread_create, {thread_create}",
        "HOSTCALL thread_destroy, {thread_destroy}",
        "HOSTCALL thread_run, {thread_run}",
        "HOSTCALL thread_set_pac, {thread_set_pac}",
        "HOSTCALL kernel_map, {kernel_map}",
        "HOSTCALL kernel_unmap, {kernel_unmap}",
        "HOSTCALL mmio_emulate, {mmio_emulate}",
        "HOSTCALL irq_take, {irq_take}",
        // ---- signal entry: void xh_sig_entry(int, siginfo_t *, void *) -----------------------------------------
        // A vCPU thread takes signals on its own signal stack, a 1 MiB aligned block of the arena whose first word is
        // its struct xh_cpu *. The interrupted code may have been the kernel, with its own TPIDR_EL0 and x18: put the
        // host's back before any Rust runs, and the interrupted ones after.
        ".text",
        ".globl xh_sig_entry",
        ".type xh_sig_entry, %function",
        ".p2align 2",
        "xh_sig_entry:",
        "stp x29, x30, [sp, #-48]!",
        "mov x29, sp",
        "stp x19, x20, [sp, #16]",
        "str x21, [sp, #32]",
        "mov x19, #0",
        "adrp x9, {arena}",
        "add x9, x9, :lo12:{arena}",
        "ldp x10, x11, [x9]", // arena [lo, hi)
        "mov x12, sp",
        "cmp x12, x10",
        "b.lo 1f",
        "cmp x12, x11",
        "b.hs 1f",
        "and x12, x12, #0xfffffffffff00000",
        "ldr x19, [x12]",
        "mrs x20, tpidr_el0",
        "mov x21, x18",
        "ldr x9, [x19, #{h_tpidr}]",
        "msr tpidr_el0, x9",
        "ldr x18, [x19, #{h_x18}]",
        "1:",
        "mov x3, x19",
        "bl {signal}",
        "cbz x19, 2f",
        "msr tpidr_el0, x20",
        "mov x18, x21",
        "2:",
        "ldr x21, [sp, #32]",
        "ldp x19, x20, [sp, #16]",
        "ldp x29, x30, [sp], #48",
        "ret",
        ".size xh_sig_entry, . - xh_sig_entry",
        // ---- where a diverted kernel context lands: x0 = cpu, x1 = frame, x2 = the kernel's upcall --------------
        // Kernel context, on the interrupted stack just below the frame.
        ".globl xh_upcall_tramp",
        ".type xh_upcall_tramp, %function",
        ".p2align 2",
        "xh_upcall_tramp:",
        "mov x19, x0",
        "mov x20, x1",
        "mov x29, #0",
        "blr x2",
        "mov x0, x19",
        "mov x1, x20",
        "b xh_hc_frame_resume", // does not return
        ".size xh_upcall_tramp, . - xh_upcall_tramp",
        // ---- void xh_arch_enter(cpu, entry, a0, a1, a2, sp): leave the host for the kernel, for good -------------
        ".globl xh_arch_enter",
        ".type xh_arch_enter, %function",
        ".p2align 2",
        "xh_arch_enter:",
        "mov x9, x1",
        "mov sp, x5",
        "mov x10, x0",
        "mov x0, x2",
        "mov x1, x3",
        "mov x2, x4",
        "msr tpidr_el0, xzr",
        "mov x29, #0",
        "mov x30, #0",
        "str wzr, [x10, #{in_host}]",
        "br x9",
        ".size xh_arch_enter, . - xh_arch_enter",
        // ---- void xh_arch_sigreturn(cpu, sigframe, kernel_tpidr, kernel_x18_unused, masked) ------------------------
        // The last step of frame_resume: async signals are blocked; the frame's uc_sigmask unblocks them.
        ".globl xh_arch_sigreturn",
        ".type xh_arch_sigreturn, %function",
        ".p2align 2",
        "xh_arch_sigreturn:",
        "str w4, [x0, #{masked}]",
        "msr tpidr_el0, x2",
        "str wzr, [x0, #{in_host}]",
        "mov sp, x1",
        "mov x8, #139", // rt_sigreturn
        "svc #0",
        "brk #0x1",
        ".size xh_arch_sigreturn, . - xh_arch_sigreturn",
        masked = const offset_of!(XhCpu, irq_masked),
        pending = const offset_of!(XhCpu, irq_pending),
        in_host = const offset_of!(XhCpu, in_host),
        k_tpidr = const offset_of!(XhCpu, kernel_tpidr),
        k_x18 = const offset_of!(XhCpu, kernel_x18),
        h_tpidr = const offset_of!(XhCpu, host_tpidr),
        h_x18 = const offset_of!(XhCpu, host_x18),
        h_sp = const offset_of!(XhCpu, host_sp),
        irq_poll = sym kctx::xh_kctx_irq_poll,
        arena = sym cpu::xh_sig_arena,
        signal = sym cpu::xh_cpu_signal,
        console_write = sym h::console_write,
        halt = sym h::halt,
        ready = sym h::ready,
        set_upcalls = sym h::set_upcalls,
        wall_time = sym h::wall_time,
        cpu_start = sym h::cpu_start,
        cpu_idle = sym h::cpu_idle,
        irq_ack = sym h::irq_ack,
        irq_eoi = sym h::irq_eoi,
        irq_enable = sym h::irq_enable,
        ipi = sym h::ipi,
        timer_set = sym h::timer_set,
        frame_resume = sym h::frame_resume,
        io_map = sym h::io_map,
        mmio_read = sym h::mmio_read,
        mmio_write = sym h::mmio_write,
        ram_discard = sym h::ram_discard,
        text_fixup = sym h::text_fixup,
        task_create = sym h::task_create,
        task_destroy = sym h::task_destroy,
        task_map = sym h::task_map,
        task_unmap = sym h::task_unmap,
        task_protect = sym h::task_protect,
        task_read = sym h::task_read,
        task_write = sym h::task_write,
        thread_create = sym h::thread_create,
        thread_destroy = sym h::thread_destroy,
        thread_run = sym h::thread_run,
        thread_set_pac = sym h::thread_set_pac,
        kernel_map = sym h::kernel_map,
        kernel_unmap = sym h::kernel_unmap,
        mmio_emulate = sym h::mmio_emulate,
        irq_take = sym h::irq_take,
    );
}
